type EnvelopeKind = Extract<GenUiKind, 'task-list' | 'job-status' | 'result' | 'error'>;

type EnvelopeInput = {
  kind: EnvelopeKind;
  id: string;
  title?: string;
  summary?: string;
  sections: Array<Record<string, unknown>>;
  fallbackText?: string;
  actions?: Array<Record<string, unknown>>;
  citations?: Array<Record<string, unknown>>;
  aiGenerated?: boolean;
  metadata?: Record<string, unknown>;
  responseMode?: unknown;
  status?: GenUiState;
};

const workspaceInputSchema = z.object({
  limit: z.number().int().min(1).max(20).optional(),
});

const jobInputSchema = z.object({
  jobId: z.string().min(1).optional(),
  limit: z.number().int().min(1).max(10).optional(),
});

const renderInputSchema = z.object({
  envelope: z.record(z.unknown()),
});

function clip(value: string | undefined, max = 1200): string | undefined {
  if (!value) return undefined;
  return value.length <= max ? value : `${value.slice(0, max)}\n(일부 생략됨)`;
}

function itemToSectionItem(item: Item): Record<string, unknown> {
  return { id: String(item.id), label: item.title, status: item.status };
}

function jobToSectionItem(job: AgentJob): Record<string, unknown> {
  return {
    id: job.id,
    label: job.prompt,
    status: job.status,
    description: job.finishedAt ? `완료 시각: ${job.finishedAt}` : undefined,
  };
}

function createEnvelope(input: EnvelopeInput): GenUiEnvelopeV1 {
  return sanitizeMcpEnvelope(GenUiEnvelopeV1Schema.parse({
    schemaVersion: GENUI_SCHEMA_VERSION,
    kind: input.kind,
    id: input.id,
    correlationId: randomUUID(),
    status: input.status ?? (input.kind === 'result' ? 'complete' : input.kind === 'error' ? 'error' : 'ready'),
    title: input.title,
    summary: input.summary,
    sections: input.sections,
    actions: input.actions ?? [],
    citations: input.citations ?? [],
    aiGenerated: input.aiGenerated ?? false,
    fallbackText: input.fallbackText,
    ...(input.metadata ? { metadata: input.metadata } : {}),
    ...(input.responseMode ? { responseMode: input.responseMode } : {}),
  }));
}

const SENSITIVE_METADATA_KEY = /(api[_-]?key|secret|token|password|authorization|provider[_-]?url|base[_-]?url|endpoint)/i;
const URL_VALUE = /\b(?:https?|wss?):\/\//i;

function normalizeResponseMode(value: unknown): GenUiResponseMode | undefined {
  const parsed = GenUiResponseModeSchema.safeParse(value);
  if (!parsed.success) return undefined;

  const availability = RESPONSE_MODES.map((mode) => {
    const supplied = parsed.data.availability.find((entry) => entry.mode === mode);
    return {
      mode,
      label: responseModeLabel(mode),
      configured: supplied?.configured ?? false,
      requiresServerConfiguration: mode !== 'deterministic',
    };
  });
  const selected = availability.find((entry) => entry.mode === parsed.data.mode);
  if (!selected) return undefined;
  return {
    mode: selected.mode,
    label: selected.label,
    configured: selected.configured,
    availability,
  };
}

function sanitizeMetadata(metadata: Record<string, unknown>): Record<string, unknown> {
  return Object.fromEntries(Object.entries(metadata).filter(([key, value]) => {
    if (SENSITIVE_METADATA_KEY.test(key)) return false;
    return typeof value !== 'string' || !URL_VALUE.test(value);
  }));
}

function sanitizeMcpEnvelope(envelope: GenUiEnvelopeV1): GenUiEnvelopeV1 {
  const redacted = redactSensitiveValue(envelope) as GenUiEnvelopeV1;
  const responseMode = normalizeResponseMode(envelope.responseMode);
  const sanitized = {
    ...redacted,
    metadata: sanitizeMetadata(redacted.metadata),
    ...(responseMode ? { responseMode } : {}),
  };
  if (!responseMode) delete (sanitized as Partial<GenUiEnvelopeV1>).responseMode;
  return GenUiEnvelopeV1Schema.parse(sanitized);
}

function withFallbackText(envelope: GenUiEnvelopeV1): GenUiEnvelopeV1 {
  const parsed = sanitizeMcpEnvelope(envelope);
  if (parsed.fallbackText) return parsed;
  return GenUiEnvelopeV1Schema.parse({
    ...parsed,
    fallbackText: parsed.summary ?? parsed.title ?? '요청 결과를 표시합니다.',
  });
}

function resultForEnvelope(envelope: GenUiEnvelopeV1): CallToolResult {
  const parsed = withFallbackText(envelope);
  return {
    content: [{ type: 'text', text: parsed.fallbackText! }],
    structuredContent: Object.fromEntries(Object.entries(parsed)),
  };
}

function errorResult(message: string): CallToolResult {
  const envelope = createEnvelope({
    kind: 'error',
    id: 'mcp-error',
    title: 'MCP GenUI 오류',
    summary: message,
    sections: [{ type: 'status', label: '오류', status: 'error', description: message }],
    fallbackText: message,
    status: 'error',
    metadata: { source: 'mcp', deterministic: true },
  });
  return { ...resultForEnvelope(envelope), isError: true };
}

function workspaceEnvelope(deps: McpGenUiDependencies, limit = 8, responseMode?: GenUiResponseMode): GenUiEnvelopeV1 {
  const items = deps.itemStore.list();
  const summary = deps.itemStore.summary();
  const jobs = deps.agentService.listLocalOnly(limit);
  const openItems = items.filter((item) => item.status === 'open').slice(0, limit);
  const activeJobs = jobs.filter((job) =>
    job.status === 'queued' || job.status === 'running' || job.status === 'awaiting_approval',
  );

  const itemText = openItems.length === 0
    ? '진행 중인 업무가 없습니다.'
    : openItems.map((item) => `- ${item.title}`).join('\n');
  const jobText = jobs.length === 0
    ? '최근 Codex 작업이 없습니다.'
    : jobs.map((job) => `- ${job.id}: ${job.status}`).join('\n');

  return createEnvelope({
    kind: 'task-list',
    id: 'workspace-snapshot',
    title: 'Teams 업무 허브',
    summary: `업무 ${summary.total}개 · 진행 중 ${summary.open}개 · 완료 ${summary.done}개 · 활성 작업 ${activeJobs.length}개`,
    sections: [
      {
        type: 'stats',
        title: '업무 요약',
        stats: [
          { label: '전체', value: summary.total },
          { label: '진행 중', value: summary.open },
          { label: '완료', value: summary.done },
          { label: '활성 Codex', value: activeJobs.length },
        ],
      },
      {
        type: 'list',
        title: '진행 중인 업무',
        items: openItems.map(itemToSectionItem),
      },
      {
        type: 'list',
        title: '최근 Codex 작업',
        items: jobs.map(jobToSectionItem),
      },
    ],
    fallbackText: `${itemText}\n\n${jobText}`,
    metadata: { source: 'teams-workspace', deterministic: true },
    responseMode,
  });
}

function jobEnvelope(job: AgentJob | undefined, limit = 8, responseMode?: GenUiResponseMode): GenUiEnvelopeV1 {
  if (!job) {
    return createEnvelope({
      kind: 'job-status',
      id: 'job-status',
      title: 'Codex 작업 상태',
      summary: '요청한 작업을 찾을 수 없습니다.',
      sections: [{ type: 'status', status: 'not-found' }],
      fallbackText: '요청한 Codex 작업을 찾을 수 없습니다.',
      metadata: { source: 'teams-workspace', deterministic: true },
      responseMode,
    });
  }

  const statusText = `작업 ${job.id}: ${job.status}`;
  return createEnvelope({
    kind: 'job-status',
    id: job.id,
    title: 'Codex 작업 상태',
    summary: statusText,
    sections: [
      {
        type: 'status',
        status: job.status,
        description: [
          `모드: ${job.mode}`,
          `생성: ${job.createdAt}`,
          job.startedAt ? `시작: ${job.startedAt}` : undefined,
          job.finishedAt ? `완료: ${job.finishedAt}` : undefined,
          job.threadId ? `스레드: ${job.threadId}` : undefined,
          job.commitHash ? `커밋: ${job.commitHash}` : undefined,
          clip(job.error),
          clip(job.result),
        ].filter(Boolean).join('\n'),
      },
      {
        type: 'list',
        title: '최근 진행 기록',
        items: job.progress.slice(-limit).map((message, index) => ({
          id: `${job.id}-progress-${index}`,
          label: message,
        })),
      },
    ],
    fallbackText: [
      statusText,
      job.error,
      job.result,
      job.progress.length > 0 ? job.progress.slice(-limit).join('\n') : undefined,
    ].filter(Boolean).join('\n\n'),
    metadata: { source: 'teams-workspace', deterministic: true },
    responseMode,
  });
}

async function resolveWidgetHtml(options: McpGenUiServerOptions): Promise<string> {
  if (typeof options.widgetHtml === 'string') return validateWidgetHtml(options.widgetHtml);
  if (typeof options.widgetHtml === 'function') return validateWidgetHtml(await options.widgetHtml());

  const widgetPath = options.widgetHtmlPath ?? path.resolve(process.cwd(), 'dist/mcp-widget/index.html');
  try {
    return validateWidgetHtml(await fs.readFile(widgetPath, 'utf8'));
  } catch (error) {
    const reason = error instanceof Error ? error.message : 'unknown error';
    throw new Error(`MCP GenUI 위젯 산출물을 찾을 수 없습니다: ${widgetPath} (${reason}). node scripts/build-mcp-widget.mjs를 먼저 실행하세요.`);
  }
}

function validateWidgetHtml(value: string): string {
  if (!/^\s*(?:<!doctype\s+html\b|<html\b)/i.test(value)) {
    throw new Error('MCP GenUI 위젯 리소스가 유효한 HTML 문서가 아닙니다.');
  }
  return value;
}

function registerTools(server: McpServer, options: McpGenUiServerOptions): void {
  const responseMode = normalizeResponseMode(options.responseMode);
  if (options.includeWorkspaceTools !== false) {
    registerAppTool(
      server,
      'get_workspace_snapshot',
      {
        title: 'Get workspace snapshot',
        description: 'Use this when the user asks for the current Teams workspace tasks or active Codex jobs. This is a deterministic read-only data tool; it never invents an LLM answer.',
        inputSchema: workspaceInputSchema,
        outputSchema: GenUiEnvelopeV1BaseSchema,
        annotations: {
          readOnlyHint: true,
          destructiveHint: false,
          openWorldHint: false,
          idempotentHint: true,
        },
        _meta: { ui: { visibility: ['model'] } },
      },
      async ({ limit }) => {
        const envelope = workspaceEnvelope(options, limit ?? 8, responseMode);
        return resultForEnvelope(envelope);
      },
    );
  }

  if (options.includeWorkspaceTools !== false) {
    registerAppTool(
      server,
      'get_job_status',
      {
        title: 'Get Codex job status',
        description: 'Use this when the user asks for a Codex job status. If jobId is omitted, return a deterministic list of recent jobs.',
        inputSchema: jobInputSchema,
        outputSchema: GenUiEnvelopeV1BaseSchema,
        annotations: {
          readOnlyHint: true,
          destructiveHint: false,
          openWorldHint: false,
          idempotentHint: true,
        },
        _meta: { ui: { visibility: ['model'] } },
      },
      async ({ jobId, limit }) => {
        const selected = jobId
          ? options.agentService.getLocalOnly(jobId)
          : options.agentService.listLocalOnly(limit ?? 8)[0];
        const envelope = jobEnvelope(selected, limit ?? 8, responseMode);
        return resultForEnvelope(envelope);
      },
    );
  }

  registerAppTool(
    server,
    'render_workspace_response',
    {
      title: 'Render workspace response',
      description: 'Use this after a data tool has produced a GenUiEnvelopeV1 when the user needs the read-only MCP App view. It only renders supplied structured data, never calls an LLM or fetches hidden data, and rejects every envelope action (including feedback); interactive actions belong to the Teams host.',
      inputSchema: renderInputSchema,
      outputSchema: GenUiEnvelopeV1BaseSchema,
      annotations: {
        readOnlyHint: true,
        destructiveHint: false,
        openWorldHint: false,
        idempotentHint: true,
      },
      _meta: {
        ui: {
          resourceUri: MCP_GENUI_RESOURCE_URI,
          visibility: ['model'],
        },
      },
    },
    async ({ envelope }) => {
      const parsed = GenUiEnvelopeV1Schema.safeParse(envelope);
      if (!parsed.success) {
        return errorResult('render_workspace_response에는 유효한 GenUiEnvelopeV1이 필요합니다. 데이터 도구를 먼저 호출하세요.');
      }

      if (parsed.data.actions.length > 0) {
        return errorResult('MCP GenUI 위젯은 읽기 전용입니다. action 또는 feedback이 포함된 envelope는 Teams 호스트에서만 렌더링할 수 있습니다.');
      }

      return resultForEnvelope(parsed.data);
    },
  );
}

export function createMcpGenUiServer(options: McpGenUiServerOptions): McpGenUiServerInstance {
  const server = new McpServer(
    {
      name: options.serverName ?? 'teams-workspace-mcp',
      version: options.serverVersion ?? '1.0.0',
    },
    {
      instructions: 'This MCP App renders structured workspace data in a read-only widget. render_workspace_response rejects every envelope action, including feedback; interactive actions must be handled by the Teams host. It is not the Teams mobile iframe and cannot read Teams GPS directly.',
    },
  );

  registerTools(server, options);
  options.providerTools?.register(server);

  registerAppResource(
    server,
    'Teams Workspace GenUI',
    MCP_GENUI_RESOURCE_URI,
    {
      description: 'Portable read-only MCP Apps widget for rendering action-free GenUiEnvelopeV1 data. This resource is for MCP hosts such as ChatGPT or Codex, not the Teams mobile tab iframe; interactive actions are rejected by render_workspace_response.',
      mimeType: MCP_GENUI_RESOURCE_MIME_TYPE,
      _meta: {
        ui: {
          prefersBorder: false,
          csp: { connectDomains: [], resourceDomains: [] },
        },
      },
    },
    async (uri) => ({
      contents: [{
        uri: uri.toString(),
        mimeType: MCP_GENUI_RESOURCE_MIME_TYPE,
        text: await resolveWidgetHtml(options),
        _meta: {
          ui: {
            prefersBorder: false,
            csp: { connectDomains: [], resourceDomains: [] },
          },
        },
      }],
    }),
  );

  const transport = new StreamableHTTPServerTransport({
    sessionIdGenerator: options.sessionMode === 'stateless' ? undefined : () => randomUUID(),
    enableJsonResponse: options.enableJsonResponse,
    onsessioninitialized: options.onSessionInitialized,
    onsessionclosed: options.onSessionClosed,
  });
  const ready = server.connect(transport);
  let closePromise: Promise<void> | undefined;

  return {
    server,
    transport,
    ready,
    async close(): Promise<void> {
      if (!closePromise) {
        closePromise = (async () => {
          await transport.close().catch(() => undefined);
          await server.close().catch(() => undefined);
        })();
      }
      await closePromise;
    },
  };
}

type Session = McpGenUiServerInstance;

type SessionEntry = {
  session: Session;
  sessionId?: string;
  principalKey?: string;
  lastActivity: number;
  inFlight: number;
  initializing: boolean;
  closed: boolean;
  closeNotified: boolean;
  closePromise?: Promise<void>;
};

function positiveIntegerOption(value: number | undefined, fallback: number, name: string): number {
  const candidate = value ?? fallback;
  if (!Number.isFinite(candidate) || candidate <= 0) {
    throw new RangeError(`${name} must be a positive finite number`);
  }
  return Math.max(1, Math.floor(candidate));
}

function isInitializeRequestBody(body: unknown): boolean {
  const message = Array.isArray(body)
    ? body.length === 1 ? body[0] : undefined
    : body;
  if (!message || typeof message !== 'object' || Array.isArray(message)) return false;
  return (message as { method?: unknown }).method === 'initialize';
}

function normalizedPrincipalKey(principal: McpPrincipal | undefined): string | undefined {
  if (!principal) return undefined;
  const tenantId = principal.tenantId.trim();
  const requesterId = principal.requesterId.trim();
  if (
    !tenantId
    || !requesterId
    || /[\u0000-\u001f\u007f]/.test(tenantId)
    || /[\u0000-\u001f\u007f]/.test(requesterId)
  ) return undefined;
  return `${tenantId}\u0000${requesterId}`;
}

function principalBoundServerOptions(
  options: McpGenUiServerOptions,
  principal: McpPrincipal | undefined,
): McpGenUiServerOptions {
  const providerTools = principal && options.providerToolsForPrincipal
    ? options.providerToolsForPrincipal(principal)
    : options.providerTools;
  return {
    ...options,
    providerTools,
    providerToolsForPrincipal: undefined,
    resolvePrincipal: undefined,
  };
}

function rejectMissingPrincipal(response: Response): void {
  response.status(401).json({ error: 'validated MCP principal is required' });
}

export function createMcpGenUiHandler(options: McpGenUiServerOptions): RequestHandler & { close(): Promise<void> } {
  const sessions = new Map<string, SessionEntry>();
  const stateful = options.sessionMode !== 'stateless';
  const transientSessions = new Set<SessionEntry>();
  const entries = new Set<SessionEntry>();
  const sessionTtlMs = positiveIntegerOption(options.sessionTtlMs, 10 * 60 * 1000, 'sessionTtlMs');
  const maxSessions = positiveIntegerOption(options.maxSessions, 64, 'maxSessions');
  const sessionSweepIntervalMs = positiveIntegerOption(
    options.sessionSweepIntervalMs,
    Math.min(sessionTtlMs, 60 * 1000),
    'sessionSweepIntervalMs',
  );
  let sweepPromise: Promise<void> | undefined;
  let closed = false;
  let closePromise: Promise<void> | undefined;

  const removeEntry = (entry: SessionEntry): void => {
    if (entry.sessionId && sessions.get(entry.sessionId) === entry) {
      sessions.delete(entry.sessionId);
    }
    transientSessions.delete(entry);
    entries.delete(entry);
  };

  const closeEntry = (entry: SessionEntry): Promise<void> => {
    if (entry.closePromise) return entry.closePromise;

    entry.closed = true;
    removeEntry(entry);
    let resolveClose!: () => void;
    let rejectClose!: (error: unknown) => void;
    entry.closePromise = new Promise<void>((resolve, reject) => {
      resolveClose = resolve;
      rejectClose = reject;
    });
    void (async () => {
      try {
        await entry.session.close();
        if (entry.sessionId && !entry.closeNotified) {
          entry.closeNotified = true;
          await options.onSessionClosed?.(entry.sessionId);
        }
        resolveClose();
      } catch (error) {
        rejectClose(error);
      }
    })();
    return entry.closePromise;
  };

  const sweepIdleSessions = async (): Promise<void> => {
    if (!stateful || closed || sweepPromise) return;
    sweepPromise = (async () => {
      const now = Date.now();
      const idle = [...entries].filter((entry) =>
        !entry.closed
        && entry.inFlight === 0
        && now - entry.lastActivity >= sessionTtlMs,
      );
      await Promise.allSettled(idle.map((entry) => closeEntry(entry)));
    })();
    try {
      await sweepPromise;
    } finally {
      sweepPromise = undefined;
    }
  };

  const sweepTimer = stateful
    ? setInterval(() => {
      void sweepIdleSessions();
    }, sessionSweepIntervalMs)
    : undefined;
  sweepTimer?.unref?.();

  const close = (): Promise<void> => {
    if (closePromise) return closePromise;
    closed = true;
    if (sweepTimer) clearInterval(sweepTimer);
    const current = [...entries];
    closePromise = Promise.allSettled(current.map((entry) => closeEntry(entry))).then(() => undefined);
    return closePromise;
  };

  const handler: RequestHandler = async (request, response) => {
    const principal = options.resolvePrincipal?.(request, response);
    const requestPrincipalKey = options.resolvePrincipal
      ? normalizedPrincipalKey(principal)
      : undefined;
    if (options.resolvePrincipal && !requestPrincipalKey) {
      rejectMissingPrincipal(response);
      return;
    }

    const sessionId = request.header('mcp-session-id');
    const method = request.method.toUpperCase();

    if (!stateful) {
      if (method !== 'POST') {
        response.status(sessionId ? 404 : 400).json({
          error: sessionId ? 'Unknown MCP session' : 'MCP session is required for this method',
        });
        return;
      }

      let session: Session | undefined;
      try {
        session = createMcpGenUiServer(principalBoundServerOptions(options, principal));
        await session.ready;
        await session.transport.handleRequest(request, response, request.body);
      } catch (error) {
        if (!response.headersSent) {
          const message = error instanceof Error ? error.message : 'MCP request failed';
          response.status(500).json({ error: message });
        }
      } finally {
        if (session) await session.close();
      }
      return;
    }

    let entry: SessionEntry | undefined;
    if (sessionId) {
      entry = sessions.get(sessionId);
      if (!entry) {
        response.status(404).json({ error: 'Unknown MCP session' });
        return;
      }
      if (entry.principalKey !== requestPrincipalKey) {
        response.status(403).json({ error: 'MCP session is bound to a different principal' });
        return;
      }
    } else if (method === 'POST' && isInitializeRequestBody(request.body)) {
      if (closed) {
        response.status(503).json({ error: 'MCP router is closing' });
        return;
      }
      if (entries.size >= maxSessions) {
        response.status(503).json({ error: 'MCP session limit reached' });
        return;
      }

      let created: Session | undefined;
      const serverOptions: McpGenUiServerOptions = {
        ...principalBoundServerOptions(options, principal),
        onSessionInitialized: async (initializedId) => {
          if (!entry || entry.closed) throw new Error('MCP session was closed during initialization');
          entry.sessionId = initializedId;
          sessions.set(initializedId, entry);
          transientSessions.delete(entry);
          try {
            await options.onSessionInitialized?.(initializedId);
          } catch (error) {
            await closeEntry(entry);
            throw error;
          }
        },
        onSessionClosed: async (closedId) => {
          const current = sessions.get(closedId);
          if (current) {
            await closeEntry(current);
            return;
          }
          await options.onSessionClosed?.(closedId);
        },
      };

      try {
        created = createMcpGenUiServer(serverOptions);
        entry = {
          session: created,
          ...(requestPrincipalKey ? { principalKey: requestPrincipalKey } : {}),
          lastActivity: Date.now(),
          inFlight: 0,
          initializing: true,
          closed: false,
          closeNotified: false,
        };
        entries.add(entry);
        transientSessions.add(entry);
        created.transport.onclose = () => {
          void closeEntry(entry!).catch(() => undefined);
        };
        created.transport.onerror = () => {
          if (entry && (entry.initializing || !entry.sessionId)) {
            void closeEntry(entry).catch(() => undefined);
          }
        };
        await created.ready;
      } catch (error) {
        if (entry) await closeEntry(entry).catch(() => undefined);
        if (!response.headersSent) {
          const message = error instanceof Error ? error.message : 'MCP session initialization failed';
          response.status(500).json({ error: message });
        }
        return;
      }
    } else {
      response.status(400).json({ error: 'MCP session is required for this method' });
      return;
    }

    if (!entry || entry.closed) {
      response.status(404).json({ error: 'Unknown MCP session' });
      return;
    }
    entry.lastActivity = Date.now();
    entry.inFlight += 1;
    const initializationRequest = method === 'POST' && isInitializeRequestBody(request.body);
    try {
      await entry.session.transport.handleRequest(request, response, request.body);
    } catch (error) {
      if (!response.headersSent) {
        const message = error instanceof Error ? error.message : 'MCP request failed';
        response.status(500).json({ error: message });
      }
    } finally {
      entry.inFlight -= 1;
      entry.initializing = false;
      if (initializationRequest && response.statusCode >= 400) {
        await closeEntry(entry).catch(() => undefined);
      }
    }
  };

  return Object.assign(handler, { close });
}

export function createMcpGenUiRouter(options: McpGenUiServerOptions): McpGenUiRouter {
  const router = express.Router() as McpGenUiRouter;
  const handler = createMcpGenUiHandler(options);
  router.use(express.json({ limit: '1mb' }));
  router.all('/', handler);
  router.close = handler.close;
  return router;
}
